def contract_rows():
    """계약유형사전 시트에 넣을 20칸짜리 줄을 만든다(A~O + P~T).

    SCHOOL_FIELDS 에 유형명이 빠져 있으면 조용히 빈칸으로 두지 않고 바로 알린다.
    빈칸으로 두면 계획서의 관리 책임란이 통째로 비어 나가기 때문이다.
    """
    missing = [t[0] for t in CONTRACT_TYPES if t[0] not in SCHOOL_FIELDS]
    if missing:
        raise KeyError("SCHOOL_FIELDS 에 빠진 유형: " + ", ".join(missing))
    extra = [k for k in SCHOOL_FIELDS if k not in {t[0] for t in CONTRACT_TYPES}]
    if extra:
        raise KeyError("CONTRACT_TYPES 에 없는 유형: " + ", ".join(extra))
    return [tuple(t) + SCHOOL_FIELDS[t[0]] for t in CONTRACT_TYPES]
